#INNER JOIN
#Display orders with customer details
SELECT
    o.order_id,
    o.customer_id,
    c.city,
    o.restaurant_id,
    o.status
FROM orders o
INNER JOIN customers c
ON o.customer_id = c.customer_id;

#LEFT JOIN
#Display all customers and their orders
SELECT
    c.customer_id,
    c.city,
    o.order_id,
    o.status
FROM customers c
LEFT JOIN orders o
ON c.customer_id = o.customer_id;
#RIGHT JOIN
#Display all restaurants and their orders
SELECT
    r.restaurant_id,
    r.cuisine,
    o.order_id,
    o.status
FROM orders o
RIGHT JOIN restaurants r
ON o.restaurant_id = r.restaurant_id;

#MULTIPLE INNER JOIN
#Customer, order and restaurant analysis
SELECT
    c.customer_id,
    c.city AS customer_city,
    o.order_id,
    r.restaurant_id,
    r.cuisine,
    r.city AS restaurant_city,
    o.status
FROM customers c
INNER JOIN orders o
ON c.customer_id = o.customer_id
INNER JOIN restaurants r
ON o.restaurant_id = r.restaurant_id;

#JOIN + GROUP BY
#Total orders received by each restaurant
SELECT
    r.restaurant_id,
    r.cuisine,
    COUNT(o.order_id) AS total_orders
FROM restaurants r
LEFT JOIN orders o
ON r.restaurant_id = o.restaurant_id
GROUP BY r.restaurant_id, r.cuisine
ORDER BY total_orders DESC;

#JOIN + SUM + GROUP BY
#Revenue generated by each restaurant
SELECT
    r.restaurant_id,
    r.cuisine,
    ROUND(SUM(oi.quantity * oi.price), 2) AS total_revenue
FROM restaurants r
INNER JOIN orders o
ON r.restaurant_id = o.restaurant_id
INNER JOIN order_items oi
ON o.order_id = oi.order_id
WHERE o.status IN ('Delivered', 'Late')
GROUP BY r.restaurant_id, r.cuisine
ORDER BY total_revenue DESC;

#JOIN order_items and menu_items
#Analyze item-wise sales
SELECT
    m.item_id,
    m.restaurant_id,
    SUM(oi.quantity) AS total_quantity_sold,
    ROUND(SUM(oi.quantity * oi.price), 2) AS item_revenue
FROM menu_items m
INNER JOIN order_items oi
ON m.item_id = oi.item_id
GROUP BY m.item_id, m.restaurant_id
ORDER BY item_revenue DESC;





